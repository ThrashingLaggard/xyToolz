<#
.SYNOPSIS
    Installs build/post-receive into every bare repo under VersionControl/,
    together with a per-repo xy-release.conf.

.DESCRIPTION
    Run this once, and again whenever build/post-receive changes. It replaces the
    ten near-identical copy-pasted hooks (which all shared the same bugs, so every
    fix had to be applied ten times) with one file plus a two-line config.

    It writes the hook with LF endings and no BOM. This is not cosmetic: a hook
    saved with CRLF starts with "#!/bin/sh\r", and Git for Windows will report
    "bad interpreter: /bin/sh^M" -- or, worse, silently do nothing.

.PARAMETER NuGetSource
    Where packages get pushed. Default is the local folder feed NuGets/.
    For nuget.org pass the v3 URL and set -ApiKeyEnv.

.PARAMETER ApiKeyEnv
    Name of the environment variable holding the API key (NOT the key itself).
    Only needed for remote feeds. The key never lands in a file this way.
    Mutually exclusive with -ApiKeyProtectedFile; if both are given, the protected
    file wins (post-receive checks it first).

.PARAMETER ApiKeyProtectedFile
    Alternative to -ApiKeyEnv: path to a DPAPI-encrypted blob (create it once with
    `dotnet xyToolz_Exec/bin/Release/net8.0/xyToolz_Exec.dll encrypt <path>`, typing
    the real key into stdin - never as a command-line argument). DPAPI's CurrentUser
    scope means this only decrypts under the same Windows account that encrypted it,
    so this only makes sense for a single-developer local machine, not a shared build
    box or a CI runner (use -ApiKeyEnv or the GitHub Actions secret path there instead).

.PARAMETER KeyToolPath
    Path to the built xyToolz_Exec assembly used to decrypt -ApiKeyProtectedFile.
    Required if -ApiKeyProtectedFile is set. Build it first with
    `dotnet build xyToolz_Exec -c Release`.

.EXAMPLE
    pwsh build/install-hooks.ps1
    pwsh build/install-hooks.ps1 -NuGetSource https://api.nuget.org/v3/index.json -ApiKeyEnv XY_NUGET_KEY
    pwsh build/install-hooks.ps1 -NuGetSource https://api.nuget.org/v3/index.json `
        -ApiKeyProtectedFile build/nuget-api-key.protected `
        -KeyToolPath xyToolz_Exec/bin/Release/net8.0/xyToolz_Exec.dll
#>
[CmdletBinding()]
param(
    [string] $NuGetSource,
    [string] $ApiKeyEnv = '',
    [string] $ApiKeyProtectedFile = '',
    [string] $KeyToolPath = '',
    [switch] $SkipTests,
    [string] $RepoRoot
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

if (-not $RepoRoot) {
    $RepoRoot = (& git rev-parse --show-toplevel 2>$null)
    if (-not $RepoRoot) { $RepoRoot = Split-Path -Parent $PSScriptRoot }
}
$RepoRoot = (Resolve-Path $RepoRoot).Path

$mf       = Get-Content (Join-Path $RepoRoot 'build/components.json') -Raw | ConvertFrom-Json
$bareRoot = Join-Path $RepoRoot $mf.bareRepoRoot
$hookSrc  = Join-Path $RepoRoot 'build/post-receive'

if (-not (Test-Path $hookSrc)) { throw "build/post-receive fehlt." }
if (-not $NuGetSource) { $NuGetSource = (Join-Path $RepoRoot $mf.localFeed) }

if ($ApiKeyProtectedFile -and -not $KeyToolPath) {
    throw "-ApiKeyProtectedFile braucht -KeyToolPath (Pfad zur gebauten xyToolz_Exec.dll)."
}
$apiKeyProtectedFileAbs = if ($ApiKeyProtectedFile) { (Resolve-Path $ApiKeyProtectedFile).Path -replace '\\','/' } else { '' }
$keyToolPathAbs = if ($KeyToolPath) { (Resolve-Path $KeyToolPath).Path -replace '\\','/' } else { '' }

# Read once, normalise to LF, strip any BOM.
$hookBody = (Get-Content $hookSrc -Raw) -replace "`r`n", "`n"
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

$runTests = if ($SkipTests) { '0' } else { '1' }

# Absolute paths: the hook builds in a temp dir, relative feeds resolve to nothing.
$localFeedAbs  = (Join-Path $RepoRoot $mf.localFeed) -replace '\\','/'
$restoreSources = "$localFeedAbs https://api.nuget.org/v3/index.json"

# Every component repo, plus the main repo itself -- which had no hook at all,
# so pushing to xyToolz.git never built or published anything.
$targets = @()
foreach ($c in $mf.components) {
    $targets += [pscustomobject]@{ Repo = "$($c.id).git"; PkgId = $c.id; Csproj = '' }
}
$targets += [pscustomobject]@{ Repo = 'xyToolz.git'; PkgId = 'xyToolz'; Csproj = 'xyToolz/xyToolz.csproj' }

$installed = @()
foreach ($t in $targets) {
    $bare = Join-Path $bareRoot $t.Repo
    if (-not (Test-Path $bare)) {
        Write-Host "  ! Bare-Repo fehlt, uebersprungen: $bare" -ForegroundColor Yellow
        continue
    }

    $hooksDir = Join-Path $bare 'hooks'
    New-Item -ItemType Directory -Force -Path $hooksDir | Out-Null

    [System.IO.File]::WriteAllText((Join-Path $hooksDir 'post-receive'), $hookBody, $utf8NoBom)

    $conf = @(
        "# generated by build/install-hooks.ps1 -- do not edit by hand",
        "PKG_ID=`"$($t.PkgId)`"",
        "CSPROJ_REL=`"$($t.Csproj)`"",
        "NUGET_SOURCE=`"$($NuGetSource -replace '\\','/')`"",
        "NUGET_API_KEY_ENV=`"$ApiKeyEnv`"",
        "NUGET_API_KEY_PROTECTED_FILE=`"$apiKeyProtectedFileAbs`"",
        "NUGET_KEY_TOOL=`"$keyToolPathAbs`"",
        "RESTORE_SOURCES=`"$restoreSources`"",
        "RUN_TESTS=`"$runTests`""
    ) -join "`n"
    [System.IO.File]::WriteAllText((Join-Path $hooksDir 'xy-release.conf'), "$conf`n", $utf8NoBom)

    # No-op on NTFS, matters if the repos ever live on Linux/WSL.
    if ($IsLinux -or $IsMacOS) { & chmod +x (Join-Path $hooksDir 'post-receive') }

    $installed += $t.PkgId
}

Write-Host "`nHook installiert in $($installed.Count) Repos:" -ForegroundColor Green
$installed | ForEach-Object { Write-Host "  - $_" }
Write-Host "`nFeed:  $NuGetSource"
if ($ApiKeyProtectedFile) {
    Write-Host "Key:   DPAPI-verschluesselt in $apiKeyProtectedFileAbs (entschluesselt via $keyToolPathAbs)"
} elseif ($ApiKeyEnv) {
    Write-Host "Key:   aus `$env:$ApiKeyEnv"
} else {
    Write-Host "Key:   keiner (lokaler Ordner-Feed)"
}
Write-Host ""
